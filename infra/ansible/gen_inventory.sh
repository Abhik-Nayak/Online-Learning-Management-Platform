#!/usr/bin/env bash
# Builds inventory.ini from `terraform output -json`.
#   - ansible_host = PUBLIC IP  (Ansible connects over SSH from the Management Server)
#   - private_ip   = PRIVATE IP (the app talks to the DB on this)
# Usage (from anywhere):  ./infra/ansible/gen_inventory.sh
set -euo pipefail

cd "$(dirname "$0")"
TF_DIR=../terraform
OUT=inventory.ini

command -v jq >/dev/null || { echo "jq is required: sudo apt-get install -y jq" >&2; exit 1; }

TF_JSON=$(terraform -chdir="$TF_DIR" output -json)

# Read one output value, failing loudly if it is missing.
out() {
  local v
  v=$(jq -r --arg k "$1" '.[$k].value // empty' <<<"$TF_JSON")
  [[ -n "$v" ]] || { echo "Terraform output '$1' is missing. Did you run terraform apply?" >&2; exit 1; }
  echo "$v"
}

cat > "$OUT" <<EOF
# Generated by gen_inventory.sh from terraform output - do not edit by hand.

[app]
app1 ansible_host=$(out app_1_public_ip) private_ip=$(out app_1_private_ip)
app2 ansible_host=$(out app_2_public_ip) private_ip=$(out app_2_private_ip)

[db]
db1 ansible_host=$(out db_public_ip) private_ip=$(out db_private_ip)
EOF

echo "Wrote $(pwd)/$OUT:"
cat "$OUT"
